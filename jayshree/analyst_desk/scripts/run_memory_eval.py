"""Memory evaluation: each case with memory ON and OFF, scored in code (see analystdesk/memory_eval.py).

Every case gets its own fresh memory store under data/memory/eval/<tag>/ (git-ignored), so the
analyst's real memory is never read or changed. Runs stop at the note gate: nothing is published.
Lessons are switched off (AGENT_LESSONS=0) so only memory differs between the two runs.

    python scripts/run_memory_eval.py                 # all cases, C1
    python scripts/run_memory_eval.py --cases m01 m06 --mode c2
    python scripts/run_memory_eval.py --report data/evaluation/results/memory_eval_<tag>.json
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")
os.environ["AGENT_LESSONS"] = "0"
os.environ.pop("AGENT_EVAL", None)   # AGENT_EVAL=1 would force memory off for both runs

from analystdesk import memory  # noqa: E402
from analystdesk.evaluation import PRICE_PER_M, RESULTS, TIMEOUT_S  # noqa: E402
from analystdesk.memory_eval import load_cases, memory_used, score_off, score_on, seed  # noqa: E402

REPORT = ROOT / "docs" / "memory_eval.md"


async def run(rid: str, request: str, mode: str, memory_on: bool) -> dict:
    from langgraph.types import Command
    from analystdesk.agent.runtime import run_until_gate
    start = time.perf_counter()
    payload = {"request": request, "mode": mode, "memory_on": memory_on, "analyst": "memeval"}
    r = await run_until_gate(rid, payload, transport="inprocess")
    if r["interrupts"] and r["interrupts"][0]["gate"] == "plan":
        r = await run_until_gate(rid, Command(resume={"action": "approve", "approver": "memeval"}),
                                 transport="inprocess")
    v = r["values"]
    v["_seconds"] = round(time.perf_counter() - start, 1)
    return v


async def run_case(case: dict, mode: str, tag: str) -> dict:
    memory.MEMORY_DB = ROOT / "data" / "memory" / "eval" / tag / f"{case['id']}.sqlite"
    memory.MEMORY_DB.parent.mkdir(parents=True, exist_ok=True)
    memory.MEMORY_DB.unlink(missing_ok=True)
    await seed(case)
    row = {"id": case["id"], "kind": case["kind"], "request": case["request"], "mode": mode}
    for label, on in (("on", True), ("off", False)):
        rid = f"memeval-{tag}-{case['id']}-{label}"
        try:
            v = await asyncio.wait_for(run(rid, case["request"], mode, on), timeout=TIMEOUT_S)
            scored = score_on(case, v) if on else score_off(case, v)
            row[label] = {"run_id": rid, **scored, "memory_used": memory_used(v),
                          "plan_companies": (v.get("plan") or {}).get("companies"),
                          "tokens": v.get("tokens", 0), "seconds": v["_seconds"],
                          "body": (v.get("draft") or {}).get("body", "")}
        except Exception as exc:   # noqa: BLE001 — failed runs are reported, not hidden
            row[label] = {"run_id": rid, "success": False, "error": f"{type(exc).__name__}: {exc}"[:300]}
    return row


def summary(rows: list[dict]) -> dict:
    def mean(xs):
        xs = [x for x in xs if x is not None]
        return round(sum(xs) / len(xs), 1) if xs else None
    out = {"cases": len(rows)}
    for label in ("on", "off"):
        out[label] = {
            "success": sum(r[label].get("success", False) for r in rows),
            "errors": sum(1 for r in rows if r[label].get("error")),
            "tokens_mean": mean([r[label].get("tokens") for r in rows]),
            "seconds_mean": mean([r[label].get("seconds") for r in rows]),
        }
        out[label]["cost_per_case_usd"] = round((out[label]["tokens_mean"] or 0) * PRICE_PER_M / 1e6, 4)
    by_kind: dict[str, list[int]] = {}
    for r in rows:
        k = by_kind.setdefault(r["kind"], [0, 0])
        k[0] += r["on"].get("success", False)
        k[1] += 1
    out["on"]["by_kind"] = {k: f"{a}/{b}" for k, (a, b) in by_kind.items()}
    return out


def write_report(data: dict, path: Path) -> None:
    s, rows = data["summary"], data["rows"]
    lines = [
        "# Memory evaluation (memory on vs off)",
        "",
        f"Generated by `scripts/run_memory_eval.py` from `{path.name}`. {s['cases']} cases in "
        "`data/evaluation/memory_cases.jsonl`; mode "
        f"{rows[0]['mode'].upper() if rows else '-'}; same model, tools and budget for both runs; "
        "lessons off; each case seeds its own fresh memory store; runs stop at the note gate "
        "(nothing published). Scored in code by `analystdesk/memory_eval.py`.",
        "",
        "| | Memory ON | Memory OFF |",
        "|---|---|---|",
        f"| Cases passed | **{s['on']['success']}/{s['cases']}** (memory used correctly) | "
        f"**{s['off']['success']}/{s['cases']}** (no memory text) |",
        f"| By kind | {', '.join(f'{k} {v}' for k, v in s['on']['by_kind'].items())} | |",
        f"| Errors | {s['on']['errors']} | {s['off']['errors']} |",
        f"| Tokens per case (mean) | {s['on']['tokens_mean']:,.0f} | {s['off']['tokens_mean']:,.0f} |"
        if s['on']['tokens_mean'] and s['off']['tokens_mean'] else "| Tokens per case (mean) | - | - |",
        f"| Cost per case (USD, est.) | {s['on']['cost_per_case_usd']} | {s['off']['cost_per_case_usd']} |",
        f"| Seconds per case (mean) | {s['on']['seconds_mean']} | {s['off']['seconds_mean']} |",
        "",
        "## Per case",
        "",
        "| Case | Kind | Request | Memory ON | Memory OFF | Memory read (ON) |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        on, off = r["on"], r["off"]
        if on.get("error"):
            on_txt = f"❌ error: {on['error'][:60]}"
        else:
            failed = [k for k, ok in on["checks"].items() if not ok]
            on_txt = "✅ " + ", ".join(on["checks"]) if not failed else "❌ failed " + ", ".join(failed)
        off_txt = (f"❌ error: {off['error'][:60]}" if off.get("error") else
                   "✅ clean" if off["success"] else "❌ found " + ", ".join(off["memory_text_found"]))
        used = on.get("memory_used") or {}
        used_txt = f"{used.get('preferences', 0)} pref, notes {used.get('previous_notes') or '-'}"
        lines.append(f"| {r['id']} | {r['kind']} | {r['request']} | {on_txt} | {off_txt} | {used_txt} |")
    lines += ["", "Each run is saved in the run checkpoints under its `run_id` "
              "(`memeval-<tag>-<case>-on|off`); the full note bodies are in the results JSON."]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


async def main(args) -> None:
    cases = [c for c in load_cases() if not args.cases or c["id"] in args.cases]
    rows = []
    for case in cases:
        row = await run_case(case, args.mode, args.tag)
        rows.append(row)
        on, off = row["on"], row["off"]
        failed = [k for k, ok in on.get("checks", {}).items() if not ok]
        print(f"{case['id']} {case['kind']:12} ON {'PASS' if on.get('success') else 'fail'}"
              f"{' ' + ','.join(failed) if failed else ''}{' ' + on['error'] if on.get('error') else ''}"
              f" | OFF {'clean' if off.get('success') else 'fail ' + str(off.get('memory_text_found') or off.get('error'))}",
              flush=True)
    data = {"tag": args.tag, "mode": args.mode, "summary": summary(rows), "rows": rows}
    RESULTS.mkdir(parents=True, exist_ok=True)
    path = RESULTS / f"memory_eval_{args.tag}.json"
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    write_report(data, path)
    print(json.dumps(data["summary"], indent=2))
    print(f"saved {path.relative_to(ROOT)}; report {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cases", nargs="*")
    ap.add_argument("--mode", default="c1", choices=["c1", "c2"])
    ap.add_argument("--tag", default=time.strftime("%Y%m%d-%H%M%S"))
    ap.add_argument("--report", type=Path, help="rewrite docs/memory_eval.md from a saved result")
    a = ap.parse_args()
    if a.report:
        write_report(json.loads(a.report.read_text(encoding="utf-8")), a.report)
    else:
        asyncio.run(main(a))
