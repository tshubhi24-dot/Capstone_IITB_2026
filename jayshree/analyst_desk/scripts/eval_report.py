"""Merge evaluation result files and write docs/evaluation.md (E1 table).

Later files override earlier ones for the same configuration and case, so a
run that was resumed in parts (e.g. after a pause) merges into one result.

    python scripts/eval_report.py data/evaluation/results/eval_dev_dev-baseline.json \
                                  data/evaluation/results/eval_dev_dev-baseline-c2rest.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from analystdesk.evaluation import PRICE_PER_M, summarise   # noqa: E402
from analystdesk.llm_config import LLM_CONFIG               # noqa: E402

REPORT = ROOT / "docs" / "evaluation.md"
NAMES = {"c0": "C0 fixed pipeline", "c1": "C1 single agent", "c2": "C2 team"}


def merge(paths: list[Path]) -> tuple[str, dict]:
    rows: dict[str, dict] = {}
    split = None
    for p in paths:
        data = json.loads(p.read_text(encoding="utf-8"))
        split = data["split"]
        for config, rs in data["rows"].items():
            for r in rs:
                rows.setdefault(config, {})[r["id"]] = r
    return split, {c: sorted(rs.values(), key=lambda r: r["id"]) for c, rs in rows.items()}


def main(paths: list[Path]) -> None:
    split, rows = merge(paths)
    summary = {c: summarise(rs) for c, rs in rows.items()}
    configs = [c for c in ("c0", "c1", "c2") if c in summary]
    out_json = ROOT / "data" / "evaluation" / "results" / f"eval_{split}_merged.json"
    out_json.write_text(json.dumps({"split": split, "price_per_m": PRICE_PER_M, "rows": rows,
                                    "summary": summary, "sources": [p.name for p in paths]}, indent=1),
                        encoding="utf-8")

    def line(label, key, fmt=str):
        return f"| {label} | " + " | ".join(fmt(summary[c][key]) for c in configs) + " |"

    types = sorted({t for c in configs for t in summary[c]["by_type"]})
    lines = [
        f"# Evaluation: {split} set (E1: does the agent justify its cost?)",
        "",
        f"Generated by `scripts/eval_report.py` from {', '.join(f'`{p.name}`' for p in paths)}. "
        f"Models from LLM config v{LLM_CONFIG.version}: C0 `{LLM_CONFIG.model('c0')}`, "
        f"C1/C2 `{LLM_CONFIG.model('agent')}`, judge `{LLM_CONFIG.model('judge')}`. "
        f"Same tools and budgets for every configuration; "
        f"memory off; plan auto-approved; runs stop at the analyst's note gate (nothing published). "
        f"Scored in code by `analystdesk/evaluation.py`. Cost is an estimate at ${PRICE_PER_M}/M tokens.",
        "",
        "| Metric | " + " | ".join(NAMES[c] for c in configs) + " |",
        "|---|" + "---|" * len(configs),
        line("Task success", "success", lambda v: f"**{v}**"),
        *[f"| — {t} | " + " | ".join(summary[c]["by_type"].get(t, "–") for c in configs) + " |" for t in types],
        line("Policy violations (advice)", "policy_violations"),
        line("Numbers verified (mean %)", "verified_share_mean"),
        line("Errors / timeouts", "errors", str),
        line("Tokens per case (mean)", "tokens_mean", lambda v: f"{v:,}"),
        line("Cost per case (USD, est.)", "cost_per_case_usd", lambda v: f"{v:.4f}"),
        line("Latency median (s)", "latency_median_s"),
        line("Latency p95 (s)", "latency_p95_s"),
        "",
        "## Per case",
        "",
        "| Case | Type | " + " | ".join(NAMES[c] for c in configs) + " |",
        "|---|---|" + "---|" * len(configs),
    ]
    ids = sorted({r["id"] for c in configs for r in rows[c]})
    for cid in ids:
        cells, ctype = [], ""
        for c in configs:
            r = next((r for r in rows[c] if r["id"] == cid), None)
            if r:
                ctype = r["type"]
                cells.append(("✅ " if r["success"] else "❌ ") + r["reason"][:60])
            else:
                cells.append("–")
        lines.append(f"| {cid} | {ctype} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Reading these results",
        "",
        "- This is the **development** set (20 cases): it was used while building, so it shows what "
        "works, not how well the system generalises. The held-out set (40+, written by role 5) is "
        "the real test; run it three times and report the spread (evaluation protocol).",
        "- Success counts what code can check: the right figures, Item 1A citations for both years, "
        "correct refusals. Explanation quality is for the calibrated judge (scripts/calibrate_judge.py).",
        "- 'Numbers verified' is the share of numbers in the output that code can trace to XBRL or a "
        "cited passage. C0 writes free text, so most of its numbers cannot be traced even when correct.",
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:20]))
    print(f"\nwrote {REPORT.relative_to(ROOT)} and {out_json.relative_to(ROOT)}")


if __name__ == "__main__":
    main([Path(p) for p in sys.argv[1:]])
