"""Write docs_notfor_submission/tools.md: every MCP tool with its schemas (L7 evidence).

Generated from the servers' published schemas, so the document cannot
drift from the code. Run:  python not_for_submission/scripts/operations/list_tools.py
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from fastmcp import Client                                           # noqa: E402

from analystdesk.servers import AGENT_TOOLS, SERVERS, WRITE_TOOLS     # noqa: E402
from analystdesk.servers import edgar_server, filings_kb, portal, sandbox  # noqa: E402

OUT = ROOT / "docs_notfor_submission" / "tools.md"
MODULES = {"filings-kb": filings_kb, "edgar": edgar_server,
           "python-sandbox": sandbox, "research-portal": portal}


def _params(schema: dict) -> list[str]:
    required = set(schema.get("required", []))
    rows = []
    for name, spec in schema.get("properties", {}).items():
        kinds = [s.get("type", s.get("$ref", "any")) for s in spec.get("anyOf", [spec])]
        kind = " or ".join(str(k) for k in kinds) if kinds else "any"
        if "enum" in spec:
            kind = " / ".join(map(str, spec["enum"]))
        extra = []
        if "default" in spec:
            extra.append(f"default {json.dumps(spec['default'])}")
        for k, label in (("minimum", "min"), ("maximum", "max")):
            if k in spec:
                extra.append(f"{label} {spec[k]}")
        rows.append(f"| `{name}` | {kind} | {'yes' if name in required else 'no'} | "
                    f"{spec.get('description', '')} {('(' + ', '.join(extra) + ')') if extra else ''} |")
    return rows


async def collect() -> dict:
    out = {}
    for name, module in MODULES.items():
        async with Client(module.mcp) as client:
            out[name] = await client.list_tools()
    return out


def main() -> None:
    servers = asyncio.run(collect())
    who = {tool: sorted(a for a, tools in AGENT_TOOLS.items() if tool in tools)
           for tools in AGENT_TOOLS.values() for tool in tools}
    lines = [
        "# MCP tools",
        "",
        "Generated by `not_for_submission/scripts/operations/list_tools.py` from the servers' published schemas.",
        "Every tool returns `ok` plus an `error` with a stable code instead of raising",
        "(see `analystdesk/servers/common.py`). Tests: `tests/test_tools.py`.",
        "",
        "| Server | Tool | Read/Write | Agents allowed |",
        "|---|---|---|---|",
    ]
    for server, tools in servers.items():
        for t in tools:
            rw = "**WRITE**" if t.name in WRITE_TOOLS else "read"
            lines.append(f"| {server} | `{t.name}` | {rw} | {', '.join(who.get(t.name, [])) or '—'} |")
    for server, tools in servers.items():
        lines += ["", f"## {server}", "", f"Module: `{SERVERS[server]}`"]
        for t in tools:
            ann = t.annotations
            lines += [
                "", f"### `{t.name}`", "",
                (t.description or "").strip(), "",
                f"Annotations: readOnlyHint={ann.readOnlyHint}, destructiveHint={ann.destructiveHint}",
                "", "| Parameter | Type | Required | Description |", "|---|---|---|---|",
                *_params(t.inputSchema),
                "", f"Output fields: {', '.join(f'`{k}`' for k in (t.outputSchema or {}).get('properties', {}))}",
            ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
